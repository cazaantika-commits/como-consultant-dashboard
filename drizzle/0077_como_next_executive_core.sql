-- COMO Next executive-office foundation
-- Additive only: no existing table is altered and no existing row is updated.

CREATE TABLE `como_next_project_access` (
  `id` int AUTO_INCREMENT NOT NULL,
  `project_id` int NOT NULL,
  `user_id` int NOT NULL,
  `access_role` enum('manager','contributor','viewer') NOT NULL DEFAULT 'viewer',
  `granted_by_user_id` int,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `como_next_project_access_pk` PRIMARY KEY (`id`),
  CONSTRAINT `como_next_access_project_user_uq` UNIQUE (`project_id`,`user_id`),
  KEY `como_next_access_user_role_idx` (`user_id`,`access_role`),
  CONSTRAINT `como_next_access_project_fk` FOREIGN KEY (`project_id`) REFERENCES `projects` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `como_next_access_user_fk` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `como_next_access_granted_by_fk` FOREIGN KEY (`granted_by_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT
);

