CREATE TABLE `como_next_actions` (
  `id` int AUTO_INCREMENT NOT NULL,
  `user_id` int NOT NULL,
  `project_id` int NOT NULL,
  `work_file_id` int NOT NULL,
  `title` varchar(500) NOT NULL,
  `description` text,
  `acceptance_criteria` text NOT NULL,
  `owner_type` enum('human','manus','team') NOT NULL DEFAULT 'human',
  `owner_user_id` int,
  `waiting_project_party_id` int,
  `action_status` enum('open','in_progress','waiting_external','completed_pending_verification','verified','cancelled') NOT NULL DEFAULT 'open',
  `priority` enum('normal','important','urgent') NOT NULL DEFAULT 'normal',
  `due_at` timestamp NULL,
  `follow_up_at` timestamp NULL,
  `attention_at` timestamp NULL,
  `evidence_reference` text,
  `source_system` varchar(64) NOT NULL DEFAULT 'como_next',
  `source_record_id` varchar(128),
  `import_batch_id` varchar(64),
  `completed_at` timestamp NULL,
  `verified_at` timestamp NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `como_next_actions_pk` PRIMARY KEY (`id`),
  CONSTRAINT `como_next_action_project_id_uq` UNIQUE (`project_id`,`id`),
  CONSTRAINT `como_next_action_source_uq` UNIQUE (`source_system`,`source_record_id`),
  KEY `como_next_action_owner_attention_idx` (`owner_type`,`owner_user_id`,`action_status`,`attention_at`),
  KEY `como_next_action_project_attention_idx` (`project_id`,`action_status`,`attention_at`),
  KEY `como_next_action_file_attention_idx` (`work_file_id`,`action_status`,`attention_at`),
  CONSTRAINT `como_next_action_user_fk` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `como_next_action_owner_fk` FOREIGN KEY (`owner_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `como_next_action_work_file_fk` FOREIGN KEY (`project_id`,`work_file_id`) REFERENCES `como_next_work_files` (`project_id`,`id`) ON DELETE RESTRICT,
  CONSTRAINT `como_next_action_waiting_party_fk` FOREIGN KEY (`project_id`,`waiting_project_party_id`) REFERENCES `como_next_project_parties` (`project_id`,`id`) ON DELETE RESTRICT,
  CONSTRAINT `como_next_action_human_owner_ck` CHECK (`owner_type` <> 'human' OR `owner_user_id` IS NOT NULL),
  CONSTRAINT `como_next_action_waiting_party_ck` CHECK (`action_status` <> 'waiting_external' OR `waiting_project_party_id` IS NOT NULL),
  CONSTRAINT `como_next_action_verified_evidence_ck` CHECK (`action_status` <> 'verified' OR `evidence_reference` IS NOT NULL),
  CONSTRAINT `como_next_action_attention_ck` CHECK (`attention_at` <=> COALESCE(`follow_up_at`,`due_at`))
);

